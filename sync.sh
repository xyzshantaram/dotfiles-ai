		"@deepseek-ai/dsh-compaction-basic"
		"@deepseek-ai/dsh-llm-pi-ai"
		"@dsh-external/dsh-session-search"
		"@xgone/dsh-remote"
		"aidos"
		"approval-comment"
		"context-meter"
		"composer-menu"
		"dsh-at-file"
		"dsh-better-markdown"
		"dsh-input-history"
		"dsh-paste-to-path"
		"durable-todos"
		"profiles-client"
		"session-archive"
		"subscriptions"
		"system-fonts"
		"tooltips"
		"log-viewer"
		"job-viewer"
		"mcp-servers"
		"tool-render"

		"dsh-plugin-better-mobile-ui"
	)
	local base=(
		"@deepseek-ai/dsh-client-ui-attachment"
		"@deepseek-ai/dsh-client-web-react"
	)
	local installed extra=0 name
	installed="$(dsh plugin --profile web list --depth 0 --json 2>"$ERR_OUT" | python3 -c '
import json, sys
try:
    data = json.load(sys.stdin)
except Exception:
    sys.exit(0)
proj = data[0] if isinstance(data, list) and data else data
if not isinstance(proj, dict):
    sys.exit(0)
for key in (proj.get("dependencies") or {}):
    print(key)
