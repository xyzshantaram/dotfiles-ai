step_patch_standard_preset_tool_subagent() {
	# Pin every subagent dispatched through the shipped `standard` preset
	# onto the `subagent` profile chain (its first route). Done by editing the
	# shipped standard preset in place: the bundle owns the dsh install on
	# this machine, and re-running sync is idempotent. A dsh reinstall that
	# re-extracts the preset would silently revert; rerun sync to restore.
	#
	# Why: subagents inherit the parent agent's provider/model unless pinned,
	# so without this the main agent's orchestrator head (e.g. hy3-free)
	# leaks into subagent dispatches and the subagent chain is never walked.
	#
	# Why not copy the preset: the user owns the install and prefers the
	# direct edit. The patch is one row in one file; no new preset directory.
	local dsh_bin dsh_pkg preset_yaml
	dsh_bin="$(command -v dsh 2>/dev/null || true)"
	if [ -z "$dsh_bin" ]; then
		echo "  WARNING: dsh not on PATH; skipping standard preset patch."
		return 0
	fi
	dsh_pkg="$(dirname "$(dirname "$(realpath "$dsh_bin")")")"
	preset_yaml="$dsh_pkg/config/agent-presets/standard/agent.cordis.yml"
	if [ ! -f "$preset_yaml" ]; then
		echo "  WARNING: standard preset not found at $(short_path "$preset_yaml"); skipping."
		return 0
	fi

	local subagent_head
	subagent_head="$(SUBAGENT_YAML="$HERE/home/settings.yaml" python3 - <<'PY'
import os, sys, yaml

# Mirrors plugins/profile-routes.ts's normalizeEntry: a chain entry may be a
# single route dict, a "provider/model" string (split on the FIRST slash, so
# a sub-provider model id like command-code/deepseek/deepseek-v4-flash keeps
# its slash), a "chain:<name>" or bare chain-name ref into the `chains` map,
# a {routes: [...]} object, or an array composing any of those in order.
def normalize_entry(entry, chains, seen=None):
    seen = seen or set()
    if (isinstance(entry, dict) and isinstance(entry.get('provider'), str) and entry.get('provider')
            and isinstance(entry.get('model'), str) and entry.get('model')):
        return [entry]
    if isinstance(entry, str):
        if entry.startswith('chain:'):
            name = entry[len('chain:'):]
            if name not in chains or name in seen:
                return []
            return normalize_entry(chains[name], chains, seen | {name})
        slash = entry.find('/')
        if slash > 0:
            return [{'provider': entry[:slash], 'model': entry[slash + 1:]}]
        if entry in chains and entry not in seen:
            return normalize_entry(chains[entry], chains, seen | {entry})
        return []
    if isinstance(entry, dict):
        routes = entry.get('routes')
        if isinstance(routes, list):
            return [r for r in routes if isinstance(r, dict) and r.get('provider') and r.get('model')]
        return []
    if isinstance(entry, list):
        out = []
        for step in entry:
            if isinstance(step, str):
                if step.startswith('chain:'):
                    name = step[len('chain:'):]
                    if name in chains and name not in seen:
                        out.extend(normalize_entry(chains[name], chains, seen | {name}))
                elif step in chains and step not in seen:
                    out.extend(normalize_entry(chains[step], chains, seen | {step}))
                elif step.find('/') > 0:
                    s = step.find('/')
                    out.append({'provider': step[:s], 'model': step[s + 1:]})
            else:
                out.extend(normalize_entry(step, chains, seen))
        return out
    return []

d = yaml.safe_load(open(os.environ['SUBAGENT_YAML'])) or {}
chains = (d.get('profile') or {}).get('chains') or {}
routes = normalize_entry(chains.get('subagent'), chains)
if not routes:
    sys.exit('no subagent chain routes in home/settings.yaml')
r = routes[0]
print(f"{r['provider']} {r['model']}")
PY
	)" || { echo "  ERROR: failed to read subagent head: $subagent_head"; return 1; }
	local s_provider="${subagent_head%% *}"
	local s_model="${subagent_head#* }"

	python3 - "$preset_yaml" "$s_provider" "$s_model" <<'PY'
import re, sys
# Comment-preserving patch of the shipped standard preset. PyYAML round-trip
# drops comments and rewrites indentation, making the resulting diff huge.
# The dsh-tool-subagent rows have a deterministic shape, so a targeted line
# scan that only touches the config block is both safe and minimal.
#
# Each row of interest (indent shown for tool-subagent nested in delegation):
#     - id: tool-subagent[-fork]
#       name: '@deepseek-ai/dsh-tool-subagent'
#       [disabled: true]            <- skipped
#       config:
#         provider: ...
#         toolName: subagent[_fork]
#         backgroundMode: continuable
#
# We insert (or replace) `agentOptions:` with the subagent head immediately
# after `backgroundMode: continuable`, matching the existing 6/8-space
# indent used by the surrounding keys.
path, provider, model = sys.argv[1], sys.argv[2], sys.argv[3]
# `agentOptions` is a field of the tool's OWN config: dsh-tool-subagent
# declares it inside `Config = z.object({...})` and reads `config.agentOptions`.
# So it must nest INSIDE `config:`, not sit beside it. A sibling key is parsed
# and then ignored, which silently leaves every child inheriting the parent's
# creation route, i.e. the orchestrator head.
# `config:` sits at 6, so its children sit at 8 and their values at 10.
key_indent = '        '    # 8: `agentOptions:` inside `config:`
val_indent = '          '  # 10: its provider/model values
legacy_key = '      '      # 6: the wrong sibling placement written before
new_block = (
    f"{key_indent}agentOptions:\n"
    f"{val_indent}provider: {provider}\n"
    f"{val_indent}model: {model}\n"
)
with open(path) as f:
    lines = f.read().splitlines(keepends=True)
def row_indent(s):
    return len(s) - len(s.lstrip(' '))
edits = 0; skipped = 0
out = []
i = 0
while i < len(lines):
    line = lines[i]
    # Anchor: a `- id:` line whose next non-blank line is
    # `name: '@deepseek-ai/dsh-tool-subagent'`.
    if (line.lstrip().startswith('- id:')
        and i + 1 < len(lines)
        and "name: '@deepseek-ai/dsh-tool-subagent'" in lines[i + 1]):
        start = i
        row_indent_val = row_indent(lines[start])
        # Walk forward to find the row's end: blank line, shallower indent,
        # or another `- ...` at the same indent.
        j = start + 1
        while j < len(lines):
            ln = lines[j]
            if not ln.strip(): break
            ind = row_indent(ln)
            if ind < row_indent_val: break
            if ind == row_indent_val and ln.lstrip().startswith('- '): break
            j += 1
        row_lines = lines[start:j]
        row_text = ''.join(row_lines)
        # Skip disabled rows (tool-subagent-codex, tool-subagent-claude-code).
        if re.search(r'^\s+disabled:\s*true\s*$', row_text, re.MULTILINE):
            skipped += 1; out.extend(row_lines); i = j; continue
        # Already pinned with these values? Leave as-is.
        # Already pinned? Two shapes exist. The LEGACY wrong shape has
        # `agentOptions:` beside `config:` (6 spaces); rewriting it in place
        # with the nested indent fixes it, because it directly follows the
        # last `config:` child. The correct shape is already nested at 8.
        legacy_pinned = re.search(
            rf'^{re.escape(legacy_key)}agentOptions:\s*$\n(?:{re.escape(legacy_key)}  (?:provider|model):[^\n]*\n)+',
            row_text, re.MULTILINE,
        )
        nested_pinned = re.search(
            rf'^{re.escape(key_indent)}agentOptions:\s*$\n(?:{re.escape(val_indent)}(?:provider|model):[^\n]*\n)+',
            row_text, re.MULTILINE,
        )
        if legacy_pinned:
            new_row_text = re.sub(
                rf'^{re.escape(legacy_key)}agentOptions:\n(?:{re.escape(legacy_key)}  (?:provider|model):[^\n]*\n)+',
                new_block, row_text, count=1, flags=re.MULTILINE,
            )
            if new_row_text != row_text:
                edits += 1; out.append(new_row_text)
            else:
                skipped += 1; out.append(row_text)
            i = j; continue
        if nested_pinned:
            new_row_text = re.sub(
                rf'^{re.escape(key_indent)}agentOptions:\n(?:{re.escape(val_indent)}(?:provider|model):[^\n]*\n)+',
                new_block, row_text, count=1, flags=re.MULTILINE,
            )
            if new_row_text != row_text:
                edits += 1; out.append(new_row_text)
            else:
                skipped += 1; out.append(row_text)
            i = j; continue
        # Not pinned: insert new_block after the row's `backgroundMode:` line.
        new_row_lines = []
        inserted = False
        for rl in row_lines:
            new_row_lines.append(rl)
            if not inserted and re.match(r'^\s+backgroundMode:[^\n]*\n$', rl):
                new_row_lines.append(new_block)
                inserted = True
        if inserted:
            edits += 1; out.extend(new_row_lines)
        else:
            skipped += 1; out.extend(row_lines)
        i = j; continue
    out.append(line)
    i += 1
if edits == 0:
    print(f'  {skipped} tool-subagent row(s) unchanged (already pinned or disabled); no change')
    sys.exit(0)
with open(path, 'w') as f:
    f.writelines(out)
print(f'  pinned {edits} tool-subagent row(s) to {provider}/{model}; {skipped} unchanged')
PY
}

step_patch_standard_preset_tool_presentation() {
	# Turn on Code Mode (dsh-agent-tool-presentation, mode: both) for the
	# shipped `standard` preset, the same way the shipped `code` preset
	# already does. `both` keeps every native tool schema visible AND adds
	# one extra tool, `run_code`, so the model may batch several tool calls
	# into one program instead of one call per step. It is additive, not a
	# swap: nothing about existing tool calls changes.
	#
	# The host codeRuntime service (`dsh-code-runtime-worker-thread`) is
	# already mounted for every `dsh web` boot by
	# dsh-web-app/cordis.patch.yml, so no runtime row is added here or
	# anywhere in this repo: "the runtime stays host-plane"
	# (dsh-agent-tool-presentation/README.md). This step only adds the
	# preset-plane row that turns presentation on for the standard preset.
	#
	# Idempotent: a second run finds the row already present and exits 0
	# unchanged. A dsh reinstall that re-extracts the preset would silently
	# revert this; rerun sync to restore, same caveat as the sibling
	# standard-preset patch steps above.
	local dsh_bin dsh_pkg preset_yaml
	dsh_bin="$(command -v dsh 2>/dev/null || true)"
	if [ -z "$dsh_bin" ]; then
		echo "  WARNING: dsh not on PATH; skipping standard preset presentation patch."
		return 0
	fi
	dsh_pkg="$(dirname "$(dirname "$(realpath "$dsh_bin")")")"
	preset_yaml="$dsh_pkg/config/agent-presets/standard/agent.cordis.yml"
	if [ ! -f "$preset_yaml" ]; then
		echo "  WARNING: standard preset not found at $(short_path "$preset_yaml"); skipping."
		return 0
	fi
	if rg -q '^\s*-\s+id:\s*tool-presentation\s*$' "$preset_yaml"; then
		echo "  tool-presentation already present in $(short_path "$preset_yaml"); no change"
		return 0
	fi
	# One-time backup before the first append, so a bad patch can be undone
	# without relying on a dsh reinstall. -n never overwrites an existing
	# backup from an earlier sync run.
	cp -n "$preset_yaml" "$preset_yaml.sync.bak"
	# No full-document YAML parse here: the shipped standard preset carries a
	# pre-existing `!!js process.platform !== 'win32'` custom tag elsewhere in
	# the file, which yaml.safe_load cannot construct and rejects outright.
	# preset_disable_tool/preset_tool_enabled above hit the same constraint
	# and solve it with a targeted regex scan instead of a full parse; this
	# step follows that same convention rather than reintroducing a parser
	# that cannot read this file.
	python3 - "$preset_yaml" <<'PY'
import re, sys
path = sys.argv[1]
with open(path) as f:
    original = f.read()
block = (
    "\n# ── presentation ────────────────────────────────────────────────────────────\n"
    "\n"
    "# Code Mode for this preset. mode: both keeps every native tool schema\n"
    "# visible and adds run_code as one extra tool. The row waits for the\n"
    "# host's codeRuntime rather than assuming it: a deployment that composes\n"
    "# no TypeScript runtime fails this preset at mount, naming this id,\n"
    "# instead of at the first request.\n"
    "- id: tool-presentation\n"
    "  name: '@deepseek-ai/dsh-agent-tool-presentation'\n"
    "  config:\n"
    "    mode: both\n"
)
patched = original.rstrip("\n") + "\n" + block
# Shape check: the exact appended row, anchored at end of file, top-level
# indent (column 0), with the right name and mode -- a targeted match, not
# a full-document parse.
row_pattern = (
    r"\n- id: tool-presentation\n"
    r"  name: '@deepseek-ai/dsh-agent-tool-presentation'\n"
    r"  config:\n"
    r"    mode: both\n\Z"
)
if not re.search(row_pattern, patched):
    print("  ERROR: patched preset failed shape validation; not writing", file=sys.stderr)
    sys.exit(1)
with open(path, "w") as f:
    f.write(patched)
import os
print("  appended tool-presentation (mode: both) to ~/" + os.path.relpath(path, os.path.expanduser("~")))
PY
	if [ $? -ne 0 ]; then
		echo "  ERROR: presentation patch failed validation; restoring backup" >&2
		cp "$preset_yaml.sync.bak" "$preset_yaml"
		return 1
	fi
}

