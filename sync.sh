		case " ${expected[*]} ${base[*]} " in
			*" $name "*) ;;
			*)
				echo "  extra plugin: $name"
				echo "    dsh plugin --profile web remove $name"
				extra=1
				;;
		esac
	done
	if [ "$extra" -eq 0 ]; then
		echo "  no extra plugins."
	else
		echo "  (informational only — sync continues despite extra plugins)" >&2
	fi
	return 0
}

step_allow_builds() {
	# pnpm refuses to run a package's install/build scripts unless its exact
	# resolved tarball URL is listed under `allowBuilds` in the web profile's
	# pnpm-workspace.yaml. Every spec in BUILD_SPECS needs that (see the list
	# comment), so add an entry for each, idempotently. The pin changes per
	# bump, so we reconstruct the codeload tarball URL the same way pnpm does
	# from the github spec (owner/repo#ref -> tarball, name = repo basename).
	local ws="$DSH_HOME/profiles/web/pnpm-workspace.yaml"
	local spec path ref name tarball key
	mkdir -p "$(dirname "$ws")"
	touch "$ws"
	for spec in "${BUILD_SPECS[@]}"; do
		path="${spec#github:}"
		ref="${spec##*#}"
		path="${path%#*}"
		name="$(basename "$path")"
		tarball="https://codeload.github.com/${path}/tar.gz/${ref}"
		key="${name}@${tarball}"
		if ! grep -qxF "  ${key}: true" "$ws"; then
			grep -q '^allowBuilds:' "$ws" || printf 'allowBuilds:\n' >> "$ws"
			awk -v k="  ${key}: true" '
				BEGIN { done=0 }
				/^allowBuilds:/ && !done { print; print k; done=1; next }
				{ print }
			' "$ws" > "$ws.tmp" && mv "$ws.tmp" "$ws"
			echo "    added allowBuilds: ${key}"
		fi
	done
}

# Run one `dsh plugin add` quietly. Silent on success, full output on failure,
# and pnpm's peer-dependency notice dropped: it fires on nearly every install in
# this bundle, because each plugin declares its own dsh peer range, and it says
# nothing actionable. VERBOSE=1 prints everything. Takes one or more specs.
dsh_plugin_add() {
	local out rc
	# rc is captured the safe way: a failing command substitution under set -e
	# aborts at the assignment before an rc=$? line runs. The old form turned
	# every install failure into a silent exit with the error still inside $out.
	if out="$(dsh plugin --profile web add "$@" 2>&1)"; then
		rc=0
	else
		rc=$?
	fi
	if [ "$rc" -ne 0 ]; then
		printf '%s\n' "$out"
		return "$rc"
	fi
	if [ "$VERBOSE" -eq 1 ]; then
		printf '%s\n' "$out"
	else
		printf '%s\n' "$out" | rg -i 'warn|error' | rg -v -i 'peer dependenc' || true
	fi
}

step_install_aidos() {
	# The aidos preset's tools run against a host-plane `aidos` core service
	# that the package's own dsh.bundle.patch mounts; `dsh plugin add`
	# installs it AND auto-mounts the patch (idempotent).
	if command -v dsh >/dev/null 2>&1; then
		echo "  installing aidos"
		dsh_plugin_add "$AIDOS_PLUGIN_SPEC"
	else
		echo "WARNING: dsh not on PATH; skipping aidos plugin install."
		echo "         Re-run './sync.sh' from a shell where dsh is installed."
	fi
}

step_sync_aidos_skills() {
	# Clone aidos at the PINNED commit from GitHub, then copy its skills/ out.
	# No local checkout is used — that would defeat the point of pinning.
	# If the pinned commit does not exist, panic and abort the whole sync.
	local spec="$AIDOS_PLUGIN_SPEC"
	local path ref owner repo url tmp
	path="${spec#github:}"
	ref="${spec##*#}"
	path="${path%#*}"
	owner="${path%%/*}"
	repo="${path##*/}"
	url="https://github.com/${owner}/${repo}.git"
	tmp="$(mktemp -d)"
	echo "=== cloning aidos skills ($url @ ${ref:0:12}) ==="
	if ! git clone "$url" "$tmp" 2>"$ERR_OUT"; then
		echo "PANIC: could not clone $url"
		rm -rf "$tmp"
		exit 1
	fi
	if ! git -C "$tmp" checkout "$ref" 2>"$ERR_OUT"; then
		echo "PANIC: pinned commit $ref does not exist in $url"
		rm -rf "$tmp"
		exit 1
	fi
	if [ ! -d "$tmp/skills" ]; then
		echo "WARNING: aidos has no skills/ directory at $ref; skipping skill sync"
		rm -rf "$tmp"
		return 0
	fi
	mkdir -p "$DSH_HOME/skills"
	cp -r "$tmp/skills/." "$DSH_HOME/skills/"
	echo "  synced aidos skills from pinned commit $ref"
	rm -rf "$tmp"
}

# Shorten an absolute path for a log line. The dsh install lives under a long
# fnm node-version path, so echoing it verbatim buries the actual message.
short_path() {
	case "$1" in
	# Everything inside the dsh install collapses to <dsh>/. That root is a
	# deep fnm node-version path, and printing it in full buries the actual
	# message in every one of these lines.
	*/node_modules/@deepseek-ai/dsh/*) printf '<dsh>/%s\n' "${1#*/node_modules/@deepseek-ai/dsh/}" ;;
	"$HOME"/*) printf '~%s\n' "${1#"$HOME"}" ;;
	*) printf '%s\n' "$1" ;;
	esac
}

# Disable one tool row (by id) in an agent preset file, in place. Idempotent:
# a row that already carries `disabled: true` is left untouched, and a row
# without a `disabled:` key gets one inserted after its `name:` line.
preset_disable_tool() {
	local file="$1" tool="$2"
	python3 - "$file" "$tool" <<'PY'
import re, sys
path, tool = sys.argv[1], sys.argv[2]
lines = open(path).readlines()
out = []
i = 0
found = False
changed = False
while i < len(lines):
    line = lines[i]
    m = re.match(r'^(\s*)-\s+id:\s*' + re.escape(tool) + r'\s*$', line)
    if not m:
        out.append(line)
        i += 1
        continue
    found = True
    row_indent = m.group(1)
    # The row runs to the next item at the same indent (or EOF).
    row = [line]
    j = i + 1
    while j < len(lines):
        ln = lines[j]
        if ln.strip():
            ind = len(ln) - len(ln.lstrip(' '))
            if ind <= len(row_indent):
                break
        row.append(ln)
        j += 1
    dis_idx = next((k for k, ln in enumerate(row) if re.match(r'^\s*disabled:', ln)), None)
    if dis_idx is not None:
        new = re.match(r'^(\s*)disabled:', row[dis_idx]).group(1) + 'disabled: true\n'
        if row[dis_idx] != new:
            row[dis_idx] = new
            changed = True
    else:
        name_idx = next((k for k, ln in enumerate(row) if re.match(r'^\s*name:', ln)), None)
        at = (name_idx + 1) if name_idx is not None else len(row)
        row.insert(at, row_indent + '  disabled: true\n')
        changed = True
    out.extend(row)
    i = j
import os
marker = '/node_modules/@deepseek-ai/dsh/'
if marker in path:
    short = '<dsh>/' + path.split(marker, 1)[1]
else:
    short = '~/' + os.path.relpath(path, os.path.expanduser('~'))
if not found:
    print(f'  WARNING: no {tool} row in {short}; nothing to disable')
    sys.exit(0)
if changed:
    open(path, 'w').writelines(out)
    print(f'  disabled {tool} in {short}')
else:
    print(f'  {tool} already disabled in {short}')
PY
}

# Exit 0 when one tool row (by id) is present but NOT disabled. Exit 1 when
# the row is absent or carries `disabled: true`. Used only by the tripwire.
preset_tool_enabled() {
	python3 - "$1" "$2" <<'PY'
import re, sys
path, tool = sys.argv[1], sys.argv[2]
lines = open(path).readlines()
for i, line in enumerate(lines):
    m = re.match(r'^(\s*)-\s+id:\s*' + re.escape(tool) + r'\s*$', line)
    if not m:
        continue
    row_indent = len(m.group(1))
    for ln in lines[i + 1:]:
        if not ln.strip():
            continue
        ind = len(ln) - len(ln.lstrip(' '))
        if ind <= row_indent:
            break
        dm = re.match(r'^\s*disabled:\s*(.+?)\s*$', ln)
        if dm:
            sys.exit(0 if dm.group(1) != 'true' else 1)
    sys.exit(0)  # row present with no disabled key: enabled
sys.exit(1)  # row absent: nothing enabled
PY
}

