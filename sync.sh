	webapp_patch="$dsh_pkg/node_modules/@deepseek-ai/dsh-web-app/cordis.patch.yml"
	if [ -f "$webapp_patch" ]; then
		preset_disable_tool "$webapp_patch" "ui-jobs"
	else
		echo "  WARNING: dsh-web-app patch not found at $(short_path "$webapp_patch"); skipping ui-jobs disable."
	fi
}

step_verify_preset_tool_disabled() {
	# Tripwire for the disable steps above. A dsh reinstall re-extracts the
	# standard preset and silently reverts an in-place patch; this step turns
	# that revert into a loud failure instead of a silent double registration
	# of the `bash` tool. Exits non-zero when tool-bash is still enabled in
	# either preset, or tool-goal in the standard preset.
	local bad=0
	local aidos_yaml="$DSH_HOME/.agent-presets/aidos/agent.cordis.yml"
	local dsh_bin dsh_pkg std_yaml
	if [ -f "$aidos_yaml" ]; then
		if preset_tool_enabled "$aidos_yaml" "tool-bash"; then
			echo "  ERROR: tool-bash is still enabled in $(short_path "$aidos_yaml")" >&2
			bad=1
		fi
	else
		echo "  WARNING: $aidos_yaml not found; skipping aidos check."
	fi
	dsh_bin="$(command -v dsh 2>/dev/null || true)"
	if [ -n "$dsh_bin" ]; then
		dsh_pkg="$(dirname "$(dirname "$(realpath "$dsh_bin")")")"
		std_yaml="$dsh_pkg/config/agent-presets/standard/agent.cordis.yml"
		if [ -f "$std_yaml" ]; then
			if preset_tool_enabled "$std_yaml" "tool-bash"; then
				echo "  ERROR: tool-bash is still enabled in $(short_path "$std_yaml")" >&2
				bad=1
			fi
			if preset_tool_enabled "$std_yaml" "tool-goal"; then
				echo "  ERROR: tool-goal is still enabled in $(short_path "$std_yaml")" >&2
				bad=1
			fi
			if preset_tool_enabled "$std_yaml" "tool-jobs"; then
				echo "  ERROR: tool-jobs is still enabled in $(short_path "$std_yaml") (job-viewer replaces it)" >&2
				bad=1
			fi
		else
			echo "  WARNING: standard preset not found at $(short_path "$std_yaml"); skipping."
		fi
		local webapp_patch="$dsh_pkg/node_modules/@deepseek-ai/dsh-web-app/cordis.patch.yml"
		if [ -f "$webapp_patch" ]; then
			if preset_tool_enabled "$webapp_patch" "ui-jobs"; then
				echo "  ERROR: ui-jobs is still enabled in $(short_path "$webapp_patch") (job-viewer replaces it)" >&2
				bad=1
			fi
		else
			echo "  WARNING: dsh-web-app patch not found at $(short_path "$webapp_patch"); skipping."
		fi
	else
		echo "  WARNING: dsh not on PATH; skipping standard preset check."
	fi
	return "$bad"
}

step_set_defaults() {
	# Regenerate $DSH_HOME/settings.yaml from the known-good repo template
	# ($HERE/home/settings.yaml). The local file is stateless: it holds no
	# secrets, so sync may overwrite it freely. profile.active is the one
	# runtime decision (the profiles tool flips it), so preserve the current
	# value; every other section comes from the template.
	local active
	active="$(python3 - "$DSH_HOME/settings.yaml" <<'PY'
import sys, yaml
try:
    d = yaml.safe_load(open(sys.argv[1])) or {}
except Exception:
    d = {}
print(d.get('profile', {}).get('active', 'personal'))
PY
)"
  echo "  regenerating settings.yaml -> $DSH_HOME/settings.yaml"
	cp "$HERE/home/settings.yaml" "$DSH_HOME/settings.yaml"
	# Strip build-time modelSync timestamp: it is local state, not template (M18)
	if rg -q "^modelSync:" "$DSH_HOME/settings.yaml"; then
		python3 - "$DSH_HOME/settings.yaml" <<'M18PY'
import pathlib, re, os
p = pathlib.Path(os.environ.get("DSH_HOME", os.path.expanduser("~/.dsh")) + "/settings.yaml")
text = p.read_text()
text = re.sub(r"\nmodelSync:\n(?:  .*\n?)*", "\n", text)
p.write_text(text)
M18PY
	fi
	# Byte-preserving patch of the single runtime line. A full YAML round-trip
	# would let PyYAML (YAML 1.1) rewrite the file, mangling e.g. the
	# reasoningEfforts key `off:` into `false: null` (YAML 1.1 treats `off` as
	# boolean), which the llm-pi-ai schema rejects and which would drop every
	# pi-ai provider. Only touch the `profile.active` value.
	if [ "$active" != "personal" ]; then
		if ! sed -i "s/^  active: .*$/  active: $active/" "$DSH_HOME/settings.yaml"; then echo "ERROR: failed to patch active" >&2; exit 1; fi
		if ! rg -q "^  active: $active$" "$DSH_HOME/settings.yaml"; then echo "ERROR: active patch had no effect (expected $active)" >&2; exit 1; fi
    echo "  set profile.active -> $active"
  fi
}

